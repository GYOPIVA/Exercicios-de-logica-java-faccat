package flamingo.java.aprendendo.basico;

public class Operadores {
    public static void main(String[] args) {
        byte numeroUm = 20;
        byte numeroDois = 30;
        int soma = numeroUm + numeroDois;
        System.out.println(soma);
        System.out.printf("%d + %d = %d", numeroUm, numeroDois, soma);
    }
}
